namespace Extrode.Pare.Lexing;

/// <summary>
/// Keyword classification of an <see cref="TokenKind.Identifier"/> token. Values from
/// <see cref="Break"/> to <see cref="With"/> are reserved words; the rest are contextual and
/// may be ordinary identifiers.
/// </summary>
internal enum Keyword : byte
{
    None,

    // Reserved words (ECMAScript ReservedWord, minus literals handled below).
    Break,
    Case,
    Catch,
    Class,
    Const,
    Continue,
    Debugger,
    Default,
    Delete,
    Do,
    Else,
    Enum,
    Export,
    Extends,
    False,
    Finally,
    For,
    Function,
    If,
    Import,
    In,
    Instanceof,
    New,
    Null,
    Return,
    Super,
    Switch,
    This,
    Throw,
    True,
    Try,
    Typeof,
    Var,
    Void,
    While,
    With,

    // Contextual: strict-mode reserved, JS contextual, and TypeScript contextual.
    Abstract,
    Accessor,
    As,
    Asserts,
    Async,
    Await,
    Constructor,
    Declare,
    From,
    Get,
    Global,
    Implements,
    Infer,
    Interface,
    Is,
    Keyof,
    Let,
    Module,
    Namespace,
    Of,
    Out,
    Override,
    Package,
    Private,
    Protected,
    Public,
    Readonly,
    Require,
    Satisfies,
    Set,
    Static,
    Type,
    Unique,
    Using,
    Yield,
}

internal static class Keywords
{
    public static bool IsReserved(Keyword k) => k is >= Keyword.Break and <= Keyword.With;

    public static Keyword Lookup(ReadOnlySpan<char> s) => s switch
    {
        "abstract" => Keyword.Abstract,
        "accessor" => Keyword.Accessor,
        "as" => Keyword.As,
        "asserts" => Keyword.Asserts,
        "async" => Keyword.Async,
        "await" => Keyword.Await,
        "break" => Keyword.Break,
        "case" => Keyword.Case,
        "catch" => Keyword.Catch,
        "class" => Keyword.Class,
        "const" => Keyword.Const,
        "constructor" => Keyword.Constructor,
        "continue" => Keyword.Continue,
        "debugger" => Keyword.Debugger,
        "declare" => Keyword.Declare,
        "default" => Keyword.Default,
        "delete" => Keyword.Delete,
        "do" => Keyword.Do,
        "else" => Keyword.Else,
        "enum" => Keyword.Enum,
        "export" => Keyword.Export,
        "extends" => Keyword.Extends,
        "false" => Keyword.False,
        "finally" => Keyword.Finally,
        "for" => Keyword.For,
        "from" => Keyword.From,
        "function" => Keyword.Function,
        "get" => Keyword.Get,
        "global" => Keyword.Global,
        "if" => Keyword.If,
        "implements" => Keyword.Implements,
        "import" => Keyword.Import,
        "in" => Keyword.In,
        "infer" => Keyword.Infer,
        "instanceof" => Keyword.Instanceof,
        "interface" => Keyword.Interface,
        "is" => Keyword.Is,
        "keyof" => Keyword.Keyof,
        "let" => Keyword.Let,
        "module" => Keyword.Module,
        "namespace" => Keyword.Namespace,
        "new" => Keyword.New,
        "null" => Keyword.Null,
        "of" => Keyword.Of,
        "out" => Keyword.Out,
        "override" => Keyword.Override,
        "package" => Keyword.Package,
        "private" => Keyword.Private,
        "protected" => Keyword.Protected,
        "public" => Keyword.Public,
        "readonly" => Keyword.Readonly,
        "require" => Keyword.Require,
        "return" => Keyword.Return,
        "satisfies" => Keyword.Satisfies,
        "set" => Keyword.Set,
        "static" => Keyword.Static,
        "super" => Keyword.Super,
        "switch" => Keyword.Switch,
        "this" => Keyword.This,
        "throw" => Keyword.Throw,
        "true" => Keyword.True,
        "try" => Keyword.Try,
        "type" => Keyword.Type,
        "typeof" => Keyword.Typeof,
        "unique" => Keyword.Unique,
        "using" => Keyword.Using,
        "var" => Keyword.Var,
        "void" => Keyword.Void,
        "while" => Keyword.While,
        "with" => Keyword.With,
        "yield" => Keyword.Yield,
        _ => Keyword.None,
    };
}
